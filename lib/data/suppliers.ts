const GRADIENTS: [string, string][] = [
  ["#E8C9A8", "#B5674A"],
  ["#C9D4BC", "#6B7A5E"],
  ["#EAD9A8", "#B08A3E"],
  ["#C9CCC0", "#5C5748"],
  ["#E3C4B8", "#9C5540"],
  ["#BFCBC2", "#56634A"],
  ["#DCC9DB", "#8A6E82"],
  ["#D9CBB4", "#7A6A4F"],
];

let gradientCursor = 0;
function nextGradient(): [string, string] {
  const g = GRADIENTS[gradientCursor % GRADIENTS.length];
  gradientCursor += 1;
  return g;
}

function s(partial: Omit<SupplierProfile, "photoGradient" | "initials"> & { initials?: string }): SupplierProfile {
  return {
    ...partial,
    initials: partial.initials ?? partial.companyName.slice(0, 2).toUpperCase(),
    photoGradient: nextGradient(),
  };
}

